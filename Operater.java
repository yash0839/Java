class Operater {
    public static void main(String[] args) {
        System.out.println(10 + 20);
        System.out.println(10 - 20);
        System.out.println(10 * 20);
        System.out.println(9 / 5);
        System.out.println(9 % 5);
        System.out.println(7.0 / 2.0);
        System.out.println(11.0 / 3.0);
    }
}